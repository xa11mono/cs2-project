const fs=require('fs');
const path=require('path');
const vm=require('vm');
const root=path.resolve(__dirname,'..');
const src=fs.readFileSync(path.join(root,'js/manager/v38-vrs-emdb-awards.js'),'utf8');
const assert=(v,m)=>{if(!v)throw new Error(m)};
const team=(name,pts)=>({name,pts,players:[],vrsLedger:{version:1,rosterKey:'',basePts:pts,matches:[],earnings:[]}});
const a=team('Alpha',920), b=team('Beta',870), c=team('Gamma',810), d=team('Delta',780), e=team('Epsilon',740), f=team('Zeta',700);
const now=1800000000000;
for(const [i,t] of [a,b,c,d,e,f].entries()){
  t.vrsLedger.earnings=[{id:`e${i}`,date:now-1000,amount:(6-i)*10000,eventName:'Prize'}];
  t.vrsLedger.matches=[{date:now-1000,opponent:'Opponent '+i,won:i%2===0,h2hDelta:i%2===0?2:-1,oppBounty:.6,network:.4,eventWeight:.8,isLAN:i%2===0}];
}
c.vrsLedger.matches=[{date:now-100*86400000,opponent:'Old rival',won:true,h2hDelta:22,oppBounty:.8,network:.7,eventWeight:1,isLAN:true}];
const window={};
const sandbox={window,teams:[a,b,c,d,e,f],seasonState:{calendar:{currentMs:now}},console:{info(){},warn(){}},Date,Math,Number,String,Object,Array,Map,Set,JSON,Promise};
vm.runInNewContext(src,sandbox,{filename:'v38-vrs-emdb-awards.js'});
const model=window.CS2VRSModel;
const ev={name:'Test Cup',prizePool:120000,isLAN:true};
const da=model.delta(a,b,ev), db=model.delta(b,a,ev);
const expectedA={win:da.win,lose:da.lose}, expectedB={win:db.win,lose:db.lose};
const untouchedBefore=[c.pts,d.pts,e.pts,f.pts];
const applied=model.applyMatch(a,b,'Alpha',ev,{});
assert(applied && applied.a.win===expectedA.win && applied.a.lose===expectedA.lose,'incremental apply must preserve the legacy A-side H2H preview');
assert(applied.b.win===expectedB.win && applied.b.lose===expectedB.lose,'incremental apply must preserve the legacy B-side H2H preview');
assert(a.vrsLedger.matches.at(-1).won===true && b.vrsLedger.matches.at(-1).won===false,'the correct winner and loser ledgers must receive entries');
assert(c.pts===untouchedBefore[0] && d.pts===untouchedBefore[1] && e.pts===untouchedBefore[2] && f.pts===untouchedBefore[3],'unrelated teams must not be recalculated after a two-team match');
const applyBody=src.slice(src.indexOf('  function applyMatch(a,b,winner,ev,match) {'),src.indexOf('  function recordParallelFinish(',src.indexOf('  function applyMatch(a,b,winner,ev,match) {')));
const fastPath=applyBody.slice(applyBody.indexOf('    ensureTeam(a); ensureTeam(b);'));
assert(!fastPath.includes('recalcAll()') && !fastPath.includes('delta(a,b') && !fastPath.includes('delta(b,a'),'normal background match path must not rescore the full league or clone all team ledgers');
assert(src.includes('offeredReferenceForLiveTeams(now)'),'match scoring must reuse a day/revision keyed global reference');
const sameDayRecalc=model.audit().fullRecalcCount;
const gammaSameDay=c.pts;
model.applyMatch(a,b,'Beta',ev,{});
assert(model.audit().fullRecalcCount===sameDayRecalc,'multiple matches on the same game day must not trigger repeated full-league recalculations');
assert(c.pts===gammaSameDay,'unrelated teams remain stable while the virtual game day is unchanged');
const beforeAgeRefresh=c.pts;
sandbox.seasonState.calendar.currentMs=now+181*86400000;
model.applyMatch(a,b,'Alpha',ev,{});
assert(model.audit().fullRecalcCount===sameDayRecalc+1,'a new virtual game day must trigger exactly one full refresh of age-weighted VRS values');
assert(c.pts!==beforeAgeRefresh,'unrelated teams must still receive the daily decay refresh, not remain stale forever');
console.log('PASS v79: incremental VRS match scoring preserves H2H deltas');
console.log('PASS v79: a background result recalculates only its two participating teams');
console.log('PASS v79: offered-reference work is cached per virtual day and earnings revision');
